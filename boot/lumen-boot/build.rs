//! Build-time asset generation for the boot loader.
//!
//! The UEFI target is soft-float and the loader should start instantly, so all
//! font rasterization happens here: Inter glyphs are rendered with fontdue at the
//! sizes the menu uses, in several sub-pixel phases, into alpha bitmaps that are
//! embedded in the binary. Gamma lookup tables for linear-light blending are
//! generated here as well.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

/// (style name in the TTC, pixel size at scale 1, sub-pixel phases)
const STRIKES: &[(&str, f32, u8)] = &[
    ("Regular", 13.0, 4),
    ("Regular", 16.0, 4),
    ("Medium", 16.0, 4),
    ("SemiBold", 40.0, 1),
];
const SCALES: &[u32] = &[1, 2];
const EXTRA_CHARS: &[char] = &['…', '·', '↑', '↓', '←', '→', '—', '–', '•', '×', '⏎'];

fn find_face(data: &[u8], style: &str) -> u32 {
    let count = ttf_parser::fonts_in_collection(data).unwrap_or(1);
    for index in 0..count {
        let face = ttf_parser::Face::parse(data, index).expect("parse face");
        let mut family = String::new();
        let mut sub = String::new();
        for name in face.names() {
            let value = name.to_string().unwrap_or_default();
            match name.name_id {
                // Typographic family/subfamily first, legacy ids as fallback.
                ttf_parser::name_id::TYPOGRAPHIC_FAMILY => family = value,
                ttf_parser::name_id::FAMILY if family.is_empty() => family = value,
                ttf_parser::name_id::TYPOGRAPHIC_SUBFAMILY => sub = value,
                ttf_parser::name_id::SUBFAMILY if sub.is_empty() => sub = value,
                _ => {}
            }
        }
        let norm = |s: &str| s.replace(' ', "").to_ascii_lowercase();
        if norm(&family) == "inter" && norm(&sub) == norm(style) {
            return index;
        }
    }
    panic!("style {style} not found in UI font");
}

fn main() {
    let font_path = env::var("LUMEN_UI_FONT").unwrap_or_else(|_| "/usr/share/fonts/inter/Inter.ttc".into());
    println!("cargo:rerun-if-env-changed=LUMEN_UI_FONT");
    println!("cargo:rerun-if-changed={font_path}");
    println!("cargo:rerun-if-changed=build.rs");
    let data = fs::read(&font_path).unwrap_or_else(|e| {
        panic!("cannot read UI font {font_path}: {e} (build inside the container or set LUMEN_UI_FONT)")
    });
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());

    let mut chars: Vec<char> = (0x20u8..0x7f).map(char::from).collect();
    chars.extend_from_slice(EXTRA_CHARS);
    chars.sort_unstable();
    chars.dedup();

    let mut code = String::new();
    code.push_str("// @generated by build.rs\n");
    code.push_str("pub static STRIKES: &[Strike] = &[\n");
    let mut strike_index = 0;
    for &scale in SCALES {
        for &(style, size, phases) in STRIKES {
            let px = size * scale as f32;
            let index = find_face(&data, style);
            let font = fontdue::Font::from_bytes(
                data.as_slice(),
                fontdue::FontSettings { collection_index: index, scale: px, ..Default::default() },
            )
            .expect("load font");
            let lm = font.horizontal_line_metrics(px).expect("line metrics");
            let mut bitmap: Vec<u8> = Vec::new();
            let mut glyphs = String::new();
            for &ch in &chars {
                if font.lookup_glyph_index(ch) == 0 && ch != ' ' {
                    continue;
                }
                for phase in 0..phases {
                    let offset = phase as f32 / phases as f32;
                    let (m, bits) = rasterize_with_offset(&font, ch, px, offset);
                    let advance = (m.advance_width * 256.0).round() as i32;
                    write!(
                        glyphs,
                        "Glyph{{ch:{},phase:{},w:{},h:{},left:{},top:{},advance:{},offset:{}}},",
                        ch as u32,
                        phase,
                        m.width,
                        m.height,
                        m.xmin,
                        // Distance from the baseline up to the bitmap's top row.
                        m.ymin + m.height as i32,
                        advance,
                        bitmap.len()
                    )
                    .unwrap();
                    bitmap.extend_from_slice(&bits);
                }
            }
            // Kerning pairs between ASCII letters/punctuation (in 1/256 px).
            let mut kern = String::new();
            for &a in &chars {
                for &b in &chars {
                    if let Some(k) = font.horizontal_kern(a, b, px) {
                        let k = (k * 256.0).round() as i32;
                        if k != 0 {
                            write!(kern, "({},{},{}),", a as u32, b as u32, k).unwrap();
                        }
                    }
                }
            }
            let bin = format!("strike{strike_index}.bin");
            fs::write(out.join(&bin), &bitmap).unwrap();
            writeln!(
                code,
                "Strike{{style:{:?},size:{},scale:{},phases:{},ascent:{},descent:{},\
                 glyphs:&[{}],kerning:&[{}],bitmap:include_bytes!(concat!(env!(\"OUT_DIR\"),\"/{}\"))}},",
                style,
                size as u32,
                scale,
                phases,
                lm.ascent.round() as i32,
                lm.descent.round() as i32,
                glyphs,
                kern,
                bin
            )
            .unwrap();
            strike_index += 1;
        }
    }
    code.push_str("];\n");

    // sRGB <-> linear light tables. Linear values use 12 bits (0..=4095).
    let to_lin: Vec<String> = (0..256)
        .map(|i| {
            let c = i as f64 / 255.0;
            let l = if c <= 0.04045 { c / 12.92 } else { ((c + 0.055) / 1.055).powf(2.4) };
            ((l * 4095.0).round() as u32).to_string()
        })
        .collect();
    let to_srgb: Vec<String> = (0..4096)
        .map(|i| {
            let l = i as f64 / 4095.0;
            let c = if l <= 0.0031308 { l * 12.92 } else { 1.055 * l.powf(1.0 / 2.4) - 0.055 };
            ((c * 255.0).round() as u32).to_string()
        })
        .collect();
    writeln!(code, "pub static SRGB_TO_LINEAR: [u16; 256] = [{}];", to_lin.join(",")).unwrap();
    writeln!(code, "pub static LINEAR_TO_SRGB: [u8; 4096] = [{}];", to_srgb.join(",")).unwrap();
    fs::write(out.join("assets.rs"), code).unwrap();
}

/// Rasterize `ch` with its origin shifted right by `offset` pixels (0 <= offset < 1).
///
/// fontdue has no sub-pixel origin parameter, so the glyph is rendered at 8x size
/// and box-filtered down with the shift applied in the 8x grid (1/8 px precision).
/// All phases (including 0) go through the same path so they look identical apart
/// from the shift. The bitmap gets a 1 px margin on every side.
fn rasterize_with_offset(font: &fontdue::Font, ch: char, px: f32, offset: f32) -> (fontdue::Metrics, Vec<u8>) {
    const K: isize = 8;
    let idx = font.lookup_glyph_index(ch);
    let (base, _) = font.rasterize_indexed(idx, px);
    if base.width == 0 || base.height == 0 {
        return (base, Vec::new());
    }
    let (big_m, big) = font.rasterize_indexed(idx, px * K as f32);
    let shift = (offset * K as f32).round() as isize;
    let xmin = base.xmin as isize - 1;
    let top = (base.ymin + base.height as i32) as isize + 1; // world y (up) of the top edge
    let w = base.width + 3;
    let h = base.height + 2;
    let big_top = (big_m.ymin + big_m.height as i32) as isize;
    let mut out = vec![0u8; w * h];
    for oy in 0..h as isize {
        for ox in 0..w as isize {
            let mut sum = 0u32;
            for sy in 0..K {
                let world_y = (top - oy) * K - 1 - sy;
                let row = big_top - 1 - world_y;
                if row < 0 || row >= big_m.height as isize {
                    continue;
                }
                for sx in 0..K {
                    let world_x = (xmin + ox) * K + sx - shift;
                    let col = world_x - big_m.xmin as isize;
                    if col < 0 || col >= big_m.width as isize {
                        continue;
                    }
                    sum += big[row as usize * big_m.width + col as usize] as u32;
                }
            }
            let n = (K * K) as u32;
            out[(oy as usize) * w + ox as usize] = ((sum + n / 2) / n).min(255) as u8;
        }
    }
    let metrics = fontdue::Metrics {
        xmin: xmin as i32,
        ymin: (top - h as isize) as i32,
        width: w,
        height: h,
        ..base
    };
    (metrics, out)
}
